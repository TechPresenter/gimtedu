import { useEffect, useState, type FormEvent } from 'react';
import { CopyPlus, Tags } from 'lucide-react';
import { Alert, Button, Field, Input, Modal, Select, Textarea, useToast } from '@/components/ui';
import { api, ApiError } from '@/lib/api';
import { formatMoney, isoDate } from '@/lib/format';
import { openPrint, useLibraryRefresh } from './shared';

export interface CopyTarget {
  id: number;
  title: string;
  price?: number | null;
  rack_no?: string | null;
}

const CONDITIONS = [
  { value: 'new', label: 'New' },
  { value: 'good', label: 'Good' },
  { value: 'fair', label: 'Fair' },
  { value: 'poor', label: 'Poor' },
];

/** Add N copies of a title at once (accession numbers + barcodes generated by the server). */
export function AddCopiesDialog({ book, onClose, onDone }: { book: CopyTarget | null; onClose: () => void; onDone?: () => void }) {
  const toast = useToast();
  const refresh = useLibraryRefresh();
  const [v, setV] = useState({ count: '1', condition: 'new', acquired_date: isoDate(), price: '', rack_no: '', remarks: '' });
  const [errors, setErrors] = useState<Record<string, string>>({});
  const [formError, setFormError] = useState<string | null>(null);
  const [saving, setSaving] = useState(false);
  const [created, setCreated] = useState<string[] | null>(null);

  useEffect(() => {
    if (book) {
      setV({ count: '1', condition: 'new', acquired_date: isoDate(), price: book.price ? String(book.price) : '', rack_no: book.rack_no ?? '', remarks: '' });
      setErrors({});
      setFormError(null);
      setCreated(null);
    }
  }, [book]);

  const set = (k: keyof typeof v, val: string) => {
    setV((s) => ({ ...s, [k]: val }));
    if (errors[k]) setErrors((e) => ({ ...e, [k]: '' }));
  };

  const submit = async (e: FormEvent) => {
    e.preventDefault();
    if (!book) return;
    const n = Number(v.count);
    if (!Number.isInteger(n) || n < 1 || n > 100) {
      setErrors({ count: 'Enter between 1 and 100 copies.' });
      return;
    }
    setSaving(true);
    setFormError(null);
    try {
      const res = await api.post<{ accession_nos: string[] }>(`library/books/${book.id}/copies`, v);
      toast.success(res.message);
      await refresh();
      onDone?.();
      setCreated(res.data.accession_nos);
    } catch (err) {
      const ex = err as ApiError;
      setErrors(ex.errors ?? {});
      setFormError(ex.message);
    } finally {
      setSaving(false);
    }
  };

  return (
    <Modal
      open={!!book}
      onClose={onClose}
      static={saving}
      size="md"
      icon={
        <span className="inline-flex h-9 w-9 shrink-0 items-center justify-center rounded-full bg-brand-100 text-brand-800 dark:bg-brand-500/20 dark:text-brand-200">
          <CopyPlus className="h-5 w-5" />
        </span>
      }
      title={created ? 'Copies added' : 'Add copies'}
      description={book?.title}
      footer={
        created ? (
          <>
            <Button variant="secondary" icon={Tags} onClick={() => openPrint('labels', { codes: created.join(',') })}>
              Print labels
            </Button>
            <Button onClick={onClose}>Done</Button>
          </>
        ) : (
          <>
            <Button variant="secondary" onClick={onClose} disabled={saving}>
              Cancel
            </Button>
            <Button type="submit" form="lib-add-copies" loading={saving}>
              Add {Number(v.count) > 1 ? `${v.count} copies` : 'copy'}
            </Button>
          </>
        )
      }
    >
      {created ? (
        <div className="space-y-3">
          <p className="text-sm text-slate-600 dark:text-slate-300">
            {created.length} new cop{created.length === 1 ? 'y is' : 'ies are'} on the shelf and available for issue.
          </p>
          <div className="flex flex-wrap gap-1.5">
            {created.map((a) => (
              <code key={a} className="rounded bg-slate-100 px-2 py-1 text-xs font-semibold text-slate-700 dark:bg-slate-800 dark:text-slate-200">
                {a}
              </code>
            ))}
          </div>
        </div>
      ) : (
        <form id="lib-add-copies" onSubmit={submit} noValidate className="grid grid-cols-1 gap-4 sm:grid-cols-2">
          {formError && <Alert variant="error" className="sm:col-span-2">{formError}</Alert>}
          <Field label="Number of copies" required htmlFor="ac-count" error={errors.count} hint="Accession numbers are generated automatically">
            <Input id="ac-count" type="number" min={1} max={100} value={v.count} onChange={(e) => set('count', e.target.value)} invalid={!!errors.count} />
          </Field>
          <Field label="Condition" htmlFor="ac-cond" error={errors.condition}>
            <Select id="ac-cond" value={v.condition} onChange={(e) => set('condition', e.target.value)} options={CONDITIONS} />
          </Field>
          <Field label="Acquired on" htmlFor="ac-date" error={errors.acquired_date}>
            <Input id="ac-date" type="date" max={isoDate()} value={v.acquired_date} onChange={(e) => set('acquired_date', e.target.value)} invalid={!!errors.acquired_date} />
          </Field>
          <Field label="Price per copy (₹)" htmlFor="ac-price" error={errors.price} hint={book?.price ? `Catalogue price ${formatMoney(book.price)}` : undefined}>
            <Input id="ac-price" type="number" min={0} step="1" value={v.price} onChange={(e) => set('price', e.target.value)} invalid={!!errors.price} />
          </Field>
          <Field label="Rack" htmlFor="ac-rack" error={errors.rack_no}>
            <Input id="ac-rack" value={v.rack_no} onChange={(e) => set('rack_no', e.target.value)} maxLength={30} placeholder="Same as the book" />
          </Field>
          <Field label="Remarks" htmlFor="ac-remarks" className="sm:col-span-2">
            <Input id="ac-remarks" value={v.remarks} onChange={(e) => set('remarks', e.target.value)} maxLength={255} placeholder="e.g. Purchased from Bookwell Distributors, invoice 2219" />
          </Field>
        </form>
      )}
    </Modal>
  );
}

const STATUS_OPTIONS = [
  { value: 'available', label: 'Available (back on shelf)' },
  { value: 'damaged', label: 'Damaged (needs repair)' },
  { value: 'lost', label: 'Lost / missing in stock check' },
  { value: 'withdrawn', label: 'Withdrawn (weeded out)' },
];

/** Change the status of copies that are not on loan. */
export function CopyStatusDialog({ ids, preset, onClose, onDone }: { ids: number[] | null; preset?: string; onClose: () => void; onDone?: () => void }) {
  const toast = useToast();
  const refresh = useLibraryRefresh();
  const [status, setStatus] = useState('damaged');
  const [remarks, setRemarks] = useState('');
  const [error, setError] = useState<string | null>(null);
  const [saving, setSaving] = useState(false);
  useEffect(() => {
    if (ids) {
      setStatus(preset ?? 'damaged');
      setRemarks('');
      setError(null);
    }
  }, [ids, preset]);

  const submit = async (e: FormEvent) => {
    e.preventDefault();
    if (!ids) return;
    setSaving(true);
    setError(null);
    try {
      const res = await api.post('library/copies/status', { ids, status, remarks });
      toast.success(res.message);
      await refresh();
      onDone?.();
      onClose();
    } catch (err) {
      setError((err as ApiError).message);
    } finally {
      setSaving(false);
    }
  };

  return (
    <Modal
      open={!!ids}
      onClose={onClose}
      static={saving}
      size="sm"
      title="Change copy status"
      description={ids ? `${ids.length} cop${ids.length === 1 ? 'y' : 'ies'} selected. Copies on loan are skipped — return them first.` : undefined}
      footer={
        <>
          <Button variant="secondary" onClick={onClose} disabled={saving}>
            Cancel
          </Button>
          <Button type="submit" form="lib-copy-status" loading={saving}>
            Update status
          </Button>
        </>
      }
    >
      <form id="lib-copy-status" onSubmit={submit} noValidate className="space-y-4">
        {error && <Alert variant="error">{error}</Alert>}
        <Field label="New status" required htmlFor="cs-status">
          <Select id="cs-status" value={status} onChange={(e) => setStatus(e.target.value)} options={STATUS_OPTIONS} />
        </Field>
        <Field label="Remarks" htmlFor="cs-remarks">
          <Textarea id="cs-remarks" rows={2} value={remarks} onChange={(e) => setRemarks(e.target.value)} maxLength={255} placeholder="e.g. Found missing during the annual stock verification" />
        </Field>
      </form>
    </Modal>
  );
}
